async (page) => {
  const results=[];
  const check=(name,value)=>{if(!value)throw new Error(name);results.push(name);};
  await page.getByRole('button',{name:'有卡点 1',exact:true}).click();
  await page.getByRole('heading',{name:'报表导出链路验证 · 演示',exact:true}).waitFor();
  check('卡点筛选及默认详情',await page.getByText('验收账号缺少导出权限',{exact:true}).isVisible());
  await page.getByRole('button',{name:'执行中 1',exact:true}).click();
  await page.getByRole('button',{name:'清单 1/3',exact:true}).click();
  check('未完成清单可见',await page.getByText('桌面交互验证',{exact:true}).isVisible());
  check('完成清单移至二级入口',await page.getByRole('button',{name:'已完成清单 1 查看 ↗',exact:true}).isVisible()&&await page.getByText('编译检查',{exact:true}).count()===0);
  await page.getByRole('button',{name:'全部 2',exact:true}).click();
  await page.getByRole('button',{name:'更多操作',exact:true}).click();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'看板设置'});
  await dialog.waitFor();
  check('默认不显示任务栏',!(await dialog.getByRole('checkbox',{name:'在任务栏中显示'}).isChecked()));
  check('默认自启关闭',!(await dialog.getByRole('checkbox',{name:'开机自启'}).isChecked()));
  await dialog.getByRole('combobox',{name:'主题'}).selectOption('dark');
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  check('取消不改变主题',await page.locator('.app.dark').count()===0);
  await page.getByRole('button',{name:'更多操作',exact:true}).click();await page.getByRole('button',{name:'设置',exact:true}).click();
  await dialog.getByRole('combobox',{name:'主题'}).selectOption('dark');await dialog.getByRole('button',{name:'保存',exact:true}).click();
  await page.locator('.app.dark').waitFor();check('黑色主题即时生效',true);
  await page.screenshot({path:'test-results/native/native-dark.png',scale:'css'});
  await page.getByRole('button',{name:'更多操作',exact:true}).click();await page.getByRole('button',{name:'设置',exact:true}).click();
  await dialog.getByRole('combobox',{name:'主题'}).selectOption('light');await dialog.getByRole('button',{name:'保存',exact:true}).click();
  await page.locator('.app:not(.dark)').waitFor();
  await page.getByRole('button',{name:'更多操作',exact:true}).click();await page.getByRole('button',{name:'Codex 接入',exact:true}).click();
  const connect=page.getByRole('dialog',{name:'Codex 接入'});
  check('一键连接入口',await connect.getByRole('button',{name:'连接 Codex',exact:true}).isVisible());
  check('差异默认隐藏',await page.locator('.diff-list').count()===0);
  await connect.getByRole('button',{name:'连接 Codex',exact:true}).click();await connect.getByText('连接成功',{exact:true}).waitFor();
  check('Rust MCP 预检与一键接入成功',true);
  await connect.getByRole('button',{name:/高级选项/}).click();await page.locator('.diff-list').waitFor();
  await connect.getByRole('button',{name:'断开连接…',exact:true}).click();
  await page.locator('.diff-list summary').first().waitFor();
  await page.locator('.diff-list summary').first().click();
  check('断开差异显示移除配置',await page.locator('.diff-list .removed').count()>0&&await page.locator('.diff-list .added').count()===0);
  check('高级差异不显示其他配置',(await page.locator('.diff-list').innerText()).includes('preserve-synthetic')===false);
  await connect.getByRole('button',{name:'确认断开',exact:true}).click();await connect.getByText('已断开连接',{exact:true}).waitFor();
  await connect.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'已完成任务 13 查看 ↗',exact:true}).click();
  check('主窗保留当前任务',await page.getByRole('heading',{name:'Windows 交互验收 · 合成',exact:true}).isVisible());
  check('主窗没有外部横向滚动',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  return {passed:results.length,checks:results};
}
